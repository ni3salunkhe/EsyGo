package com.hotelbooking.database;

import com.hotelbooking.testutil.TestDatabaseBootstrap;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
@ActiveProfiles("test")
class DatabaseSeedDataTest {

    @Autowired
    private TestDatabaseBootstrap bootstrap;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @BeforeEach
    void setUp() {
        bootstrap.resetSchema();
        bootstrap.applySeed();
    }

    @Test
    @DisplayName("DB-02: db/seed.sql applies successfully with >= 5 hotels, >= 3 locations, rooms exist, and honest sample properties")
    void seedDataMeetsAuthoringSpecification() {
        // At least 5 hotels
        Integer hotelCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM hotel", Integer.class);
        assertThat(hotelCount).isNotNull().isGreaterThanOrEqualTo(5);

        // At least 3 locations, with at least one location having >= 2 hotels
        List<String> locations = jdbcTemplate.queryForList("SELECT DISTINCT location FROM hotel", String.class);
        assertThat(locations).hasSizeGreaterThanOrEqualTo(3);

        Integer goaHotelCount = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM hotel WHERE location = 'Goa'", Integer.class
        );
        assertThat(goaHotelCount).isNotNull().isGreaterThanOrEqualTo(2);

        // 8 shared amenities
        Integer amenityCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM amenity", Integer.class);
        assertThat(amenityCount).isEqualTo(8);

        // Hotel-amenity links exist
        Integer linkCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM hotel_amenity", Integer.class);
        assertThat(linkCount).isNotNull().isGreaterThanOrEqualTo(15);

        // Rooms exist per hotel
        Integer totalRooms = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM room", Integer.class);
        assertThat(totalRooms).isNotNull().isGreaterThanOrEqualTo(20);

        // At least one small hotel with 2 rooms (for manual sold-out verification per sample-data-authoring skill)
        List<Integer> roomCounts = jdbcTemplate.queryForList(
                "SELECT COUNT(*) FROM room GROUP BY hotel_id", Integer.class
        );
        assertThat(roomCounts).contains(2);

        // image_url is strictly NULL per Decision D-14
        Integer nonNullImages = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM hotel WHERE image_url IS NOT NULL", Integer.class
        );
        assertThat(nonNullImages).isEqualTo(0);

        // hotel_image gallery contains sample images per hotel
        Integer hotelImageCount = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM hotel_image", Integer.class
        );
        assertThat(hotelImageCount).isNotNull().isGreaterThanOrEqualTo(15);

        // Seed data must NOT contain bookings or room_nights (room_nights generated by InventoryInitializer)
        Integer bookingCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM booking", Integer.class);
        assertThat(bookingCount).isEqualTo(0);

        Integer roomNightCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM room_night", Integer.class);
        assertThat(roomNightCount).isEqualTo(0);
    }
}
